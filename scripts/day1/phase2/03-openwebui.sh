_ow_rand() { head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

# _ow_split RESPONSE — sets OW_CODE and OW_BODY from the "<body>\n<code>" curl output.
_ow_split() {
  local raw="$1"
  OW_CODE="${raw##*$'\n'}"
  OW_BODY="${raw%$'\n'*}"
  [[ "$OW_CODE" =~ ^[0-9]{3}$ ]] || { OW_CODE="000"; OW_BODY="$raw"; }
}
OW_CODE=""; OW_BODY=""

# _ow_api METHOD PATH [JSON_BODY] — sets OW_CODE/OW_BODY. The bearer token goes to curl through a process substitution
# (`-H @/dev/fd/N`, curl reads header lines from a file), the body on stdin: neither is ever on argv.
_ow_api() {
  local method="$1" path="$2" body="${3:-}" raw
  if [[ -n "$OW_TOKEN" && -n "$body" ]]; then
    raw="$(curl -s --noproxy '*' --max-time 60 -X "$method" -H @<(printf 'Authorization: Bearer %s\n' "$OW_TOKEN") \
      -H 'Content-Type: application/json' --data-binary @- -w '\n%{http_code}' "$OW_URL$path" <<<"$body" 2>/dev/null || true)"
  elif [[ -n "$OW_TOKEN" ]]; then
    raw="$(curl -s --noproxy '*' --max-time 60 -X "$method" -H @<(printf 'Authorization: Bearer %s\n' "$OW_TOKEN") \
      -w '\n%{http_code}' "$OW_URL$path" 2>/dev/null || true)"
  elif [[ -n "$body" ]]; then
    raw="$(curl -s --noproxy '*' --max-time 60 -X "$method" -H 'Content-Type: application/json' --data-binary @- \
      -w '\n%{http_code}' "$OW_URL$path" <<<"$body" 2>/dev/null || true)"
  else
    raw="$(curl -s --noproxy '*' --max-time 60 -X "$method" -w '\n%{http_code}' "$OW_URL$path" 2>/dev/null || true)"
  fi
  _ow_split "$raw"
}

# _ow_json JSON PYEXPR — evaluate a python expression over the parsed JSON (bound to d); prints the result. The JSON
# travels on stdin (it may hold a token).
_ow_json() {
  python3 -c 'import json, sys
d = json.loads(sys.stdin.read())
print(eval(sys.argv[1]))' "$2" <<<"$1" 2>/dev/null
}

# _ow_keys JSON — the key names of a JSON object, never its values (what a die/warn may show of a credential response).
_ow_keys() {
  _ow_json "$1" 'sorted(d) if isinstance(d, dict) else type(d).__name__' || echo "unparsable (${#1} bytes)"
}

